    # =============================================================
    # МЕТОД СОЗДАНИЯ МЕНЮ ПРИЛОЖЕНИЯ
    # =============================================================
    
    
    def create_menu(self):
        """
        Создаёт главное меню приложения
        
        Returns:
            None: Метод добавляет меню в корневое окно
        
        Note:
            Меню содержит пункты Файл и Справка
        """
        # Создание главного меню
        menubar = tk.Menu(self.root)
        # Установка меню для корневого окна
        self.root.config(menu=menubar)
        
        # =========================================================
        # МЕНЮ ФАЙЛ
        # =========================================================
        
        # Создание подменю Файл
        file_menu = tk.Menu(menubar, tearoff=0)
        # Добавление подменю в главное меню
        menubar.add_cascade(label="Файл", menu=file_menu)
        # Добавление пункта Открыть файл
        file_menu.add_command(label="Открыть файл...", command=self.browse_input)
        # Добавление пункта Открыть конфигурацию
        file_menu.add_command(label="Открыть конфигурацию", command=self.open_config)
        # Добавление пункта Мастер настройки
        file_menu.add_command(label="Мастер настройки стилей", command=self.open_wizard)
        # Добавление разделителя
        file_menu.add_separator()
        # Добавление пункта Выход
        file_menu.add_command(label="Выход", command=self.root.quit)
        
        # =========================================================
        # МЕНЮ СПРАВКА
        # =========================================================
        
        # Создание подменю Справка
        help_menu = tk.Menu(menubar, tearoff=0)
        # Добавление подменю в главное меню
        menubar.add_cascade(label="Справка", menu=help_menu)
        # Добавление пункта Инструкция
        help_menu.add_command(label="Инструкция", command=self.show_help)
        # Добавление пункта О программе
        help_menu.add_command(label="О программе", command=self.show_about)
    
    
    # =============================================================
    # МЕТОД ОТКРЫТИЯ МАСТЕРА НАСТРОЙКИ СТИЛЕЙ
    # =============================================================
    
    
    def open_wizard(self):
        """
        Открывает мастер настройки стилей в модальном окне
        
        Returns:
            None: Метод запускает мастер и ждёт закрытия
        
        Note:
            Блокирует основное окно до закрытия мастера
        """
        # Запись в лог о запуске мастера
        self.log("🎨 Запуск мастера настройки стилей...")
        # Вызов функции запуска мастера с передачей родителя и конфига
        launch_wizard(self.root, self.config_path)
        # Запись в лог о закрытии мастера
        self.log("✅ Мастер закрыт, конфигурация обновлена")
    
    
    # =============================================================
    # МЕТОД ВЫБОРА ВХОДНОГО ФАЙЛА
    # =============================================================
    
    
    def browse_input(self):
        """
        Открывает диалог выбора входного DOCX файла
        
        Returns:
            None: Метод устанавливает путь в переменную input_path
        
        Note:
            После выбора файла автоматически генерирует имя выхода
        """
        # Открытие диалога выбора файла
        filename = filedialog.askopenfilename(
            # Заголовок диалога
            title="Выберите DOCX файл",
            # Фильтр типов файлов
            filetypes=[("Word документы", "*.docx"), ("Все файлы", "*.*")],
            # Начальная директория (домашняя папка пользователя)
            initialdir=os.path.expanduser("~")
        )
        # Проверка: выбран ли файл
        if filename:
            # Установка пути в переменную
            self.input_path.set(filename)
            # Автогенерация имени выходного файла
            self.auto_output()
            # Запись в лог о выбранном файле
            self.log(f"Выбран файл: {filename}")
    
    
    # =============================================================
    # МЕТОД ВЫБОРА ВЫХОДНОГО ФАЙЛА
    # =============================================================
    
    
    def browse_output(self):
        """
        Открывает диалог выбора места сохранения выходного файла
        
        Returns:
            None: Метод устанавливает путь в переменную output_path
        
        Note:
            По умолчанию предлагает имя с суффиксом _gost
        """
        # Открытие диалога сохранения файла
        filename = filedialog.asksaveasfilename(
            # Заголовок диалога
            title="Сохранить как",
            # Расширение по умолчанию
            defaultextension=".docx",
            # Фильтр типов файлов
            filetypes=[("Word документы", "*.docx")],
            # Имя файла по умолчанию
            initialfile=os.path.basename(self.input_path.get()).replace('.docx', '_gost.docx')
        )
        # Проверка: выбрано ли место сохранения
        if filename:
            # Установка пути в переменную
            self.output_path.set(filename)
            # Запись в лог о выходном файле
            self.log(f"Выходной файл: {filename}")
    
    
    # =============================================================
    # МЕТОД АВТОГЕНЕРАЦИИ ИМЕНИ ВЫХОДНОГО ФАЙЛА
    # =============================================================
    
    
    def auto_output(self):
        """
        Автоматически генерирует имя выходного файла на основе входного
        
        Returns:
            None: Метод устанавливает путь в переменную output_path
        
        Note:
            Добавляет суффикс _gost перед расширением .docx
        """
        # Получение пути входного файла
        input_file = self.input_path.get()
        # Проверка: указан ли входной файл
        if input_file:
            # Разделение пути на основу и расширение
            base, ext = os.path.splitext(input_file)
            # Установка выходного пути с суффиксом _gost
            self.output_path.set(f"{base}_gost{ext}")
    
    
    # =============================================================
    # МЕТОД ОТКРЫТИЯ ФАЙЛА КОНФИГУРАЦИИ
    # =============================================================
    
    
    def open_config(self):
        """
        Открывает файл конфигурации в редакторе по умолчанию
        
        Returns:
            None: Метод запускает файл через ОС
        
        Note:
            Использует os.startfile для Windows
        """
        # Проверка: существует ли файл конфигурации
        if os.path.exists(self.config_path):
            # Открытие файла в редакторе по умолчанию
            os.startfile(self.config_path)
            # Запись в лог об открытии конфигурации
            self.log("Открыт файл конфигурации")
        else:
            # Показ предупреждения если файл не найден
            messagebox.showwarning("Предупреждение", 
                                  f"Файл конфигурации не найден:\n{self.config_path}")
    
    
    # =============================================================
    # МЕТОД ПРОВЕРКИ ДОКУМЕНТА ПЕРЕД ФОРМАТИРОВАНИЕМ
    # =============================================================
    
    
    def validate_document(self):
        """
        Проверяет документ на соответствие структуре перед форматированием
        
        Returns:
            None: Метод показывает результаты в текстовом поле
        
        Note:
            Вызывает validate_file из formatter_core
        """
        # Получение пути входного файла
        input_file = self.input_path.get()
        # Проверка: выбран ли файл
        if not input_file:
            # Показ предупреждения если файл не выбран
            messagebox.showwarning("Предупреждение", "Сначала выберите файл!")
            # Выход из метода
            return
        
        # Запись в лог о начале проверки
        self.log("🔍 Проверка документа...")
        
        # Попытка проверки документа
        try:
            # Вызов функции валидации из core модуля
            result = validate_file(input_file, self.config_path)
            
            # Установка текстового поля в режим редактирования
            self.preview_text.config(state="normal")
            # Очистка текущего содержимого поля
            self.preview_text.delete("1.0", tk.END)
            
            # Проверка: валиден ли документ
            if result["valid"]:
                # Вставка сообщения об успехе
                self.preview_text.insert("1.0", "✅ Документ готов к форматированию\n\n")
            else:
                # Вставка сообщения о проблемах
                self.preview_text.insert("1.0", "❌ Обнаружены проблемы:\n\n")
            
            # Вставка информационной части
            for info in result["info"]:
                self.preview_text.insert(tk.END, f"{info}\n")
            
            # Вставка предупреждений
            for warning in result["warnings"]:
                self.preview_text.insert(tk.END, f"{warning}\n")
            
            # Установка текстового поля в режим только для чтения
            self.preview_text.config(state="disabled")
            # Запись в лог о завершении проверки
            self.log("Проверка завершена")
            
        # Обработка ошибки проверки
        except Exception as e:
            # Показ сообщения об ошибке
            messagebox.showerror("Ошибка", f"Не удалось проверить файл:\n{e}")
            # Запись в лог об ошибке
            self.log(f"❌ Ошибка проверки: {e}")
    
    
    # =============================================================
    # МЕТОД ЗАПУСКА ПРОЦЕССА ФОРМАТИРОВАНИЯ
    # =============================================================
    
    
    def run_formatter(self):
        """
        Запускает процесс форматирования в отдельном потоке
        
        Returns:
            None: Метод создаёт поток и запускает его
        
        Note:
            Блокирует кнопку запуска во время обработки
        """
        # Получение пути входного файла
        input_file = self.input_path.get()
        # Получение пути выходного файла
        output_file = self.output_path.get()
        
        # Проверка: выбран ли входной файл
        if not input_file:
            # Показ ошибки если файл не выбран
            messagebox.showerror("Ошибка", "Выберите входной файл!")
            # Выход из метода
            return
        
        # Проверка: указан ли выходной файл
        if not output_file:
            # Показ ошибки если выход не указан
            messagebox.showerror("Ошибка", "Укажите выходной файл!")
            # Выход из метода
            return
        
        # Проверка: существует ли входной файл
        if not os.path.exists(input_file):
            # Показ ошибки если файл не найден
            messagebox.showerror("Ошибка", f"Файл не найден:\n{input_file}")
            # Выход из метода
            return
        
        # Блокировка кнопки запуска
        self.run_button.config(state="disabled")
        # Сброс прогресс-бара в 0
        self.progress['value'] = 0
        # Установка текста статуса
        self.status_text.set("⏳ Обработка...")
        
        # Создание потока для форматирования
        thread = threading.Thread(target=self._format_thread, args=(input_file, output_file))
        # Установка потока как демон (завершится с приложением)
        thread.daemon = True
        # Запуск потока
        thread.start()
    
    
    # =============================================================
    # МЕТОД ПОТОКА ФОРМАТИРОВАНИЯ
    # =============================================================
    
    
    def _format_thread(self, input_file, output_file):
        """
        Поток для форматирования (чтобы не блокировать GUI)
        
        Args:
            input_file (str): Путь к входному файлу
            output_file (str): Путь к выходному файлу
        
        Returns:
            None: Метод вызывает функции форматирования
        
        Note:
            Выполняется в отдельном потоке
        """
        # Определение функции обратного вызова прогресса
        def progress_callback(value, message):
            # Вызов обновления прогресса в главном потоке
            self.root.after(0, lambda: self.update_progress(value, message))
        
        # Попытка выполнения форматирования
        try:
            # Вызов функции форматирования из core модуля
            result = format_file(
                # Путь к входному файлу
                input_file, 
                # Путь к выходному файлу
                output_file, 
                # Путь к конфигурации
                self.config_path, 
                # Флаг создания бэкапа
                self.create_backup.get(),
                # Функция обратного вызова
                progress_callback
            )
            
            # Проверка: успешно ли выполнено
            if result.get("success"):
                # Вызов обработки успеха в главном потоке
                self.root.after(0, lambda: self.format_success(result))
            else:
                # Вызов обработки ошибки в главном потоке
                self.root.after(0, lambda: self.format_error(result))
                
        # Обработка любой ошибки
        except Exception as e:
            # Вызов обработки ошибки в главном потоке
            self.root.after(0, lambda: self.format_error({"errors": [str(e)]}))
    
    
    # =============================================================
    # МЕТОД ОБНОВЛЕНИЯ ПРОГРЕСС-БАРА
    # =============================================================
    
    
    def update_progress(self, value, message):
        """
        Обновляет прогресс-бар из потока
        
        Args:
            value (int): Значение прогресса (0-100)
            message (str): Сообщение о текущем состоянии
        
        Returns:
            None: Метод обновляет виджеты напрямую
        
        Note:
            Вызывается через root.after для безопасности потоков
        """
        # Установка значения прогресс-бара
        self.progress['value'] = value
        # Обновление текста статуса
        self.status_text.set(message)
        # Запись сообщения в лог
        self.log(message)
        # Обновление интерфейса
        self.root.update_idletasks()
    
    
    # =============================================================
    # МЕТОД ОБРАБОТКИ УСПЕШНОГО ЗАВЕРШЕНИЯ
    # =============================================================
    
    
    def format_success(self, result):
        """
        Обработка успешного завершения форматирования
        
        Args:
            result (dict): Словарь с результатами форматирования
        
        Returns:
            None: Метод показывает сообщение и разблокирует интерфейс
        
        Note:
            Вызывается в главном потоке после завершения
        """
        # Установка прогресса в 100%
        self.progress['value'] = 100
        # Установка статуса успеха
        self.status_text.set("✅ Успешно выполнено!")
        # Разблокировка кнопки запуска
        self.run_button.config(state="normal")
        
        # Формирование сообщения статистики
        stats_msg = f"\n📊 Статистика:\n"
        # Добавление количества параграфов
        stats_msg += f"   Обработано параграфов: {result.get('paragraphs_processed', 0)}\n"
        # Добавление пути к файлу
        stats_msg += f"   Выходной файл: {result.get('output_path', '')}\n"
        
        # Получение статистики стилей
        styles = result.get('styles_applied', {})
        # Проверка: есть ли применённые стили
        if styles:
            # Добавление заголовка секции стилей
            stats_msg += f"\n   Применённые стили:\n"
            # Перебор топ-5 стилей по количеству
            for style, count in sorted(styles.items(), key=lambda x: -x[1])[:5]:
                # Добавление стиля в статистику
                stats_msg += f"      {style}: {count}\n"
        
        # Запись статистики в лог
        self.log(stats_msg)
        
        # Показ сообщения об успехе
        messagebox.showinfo("Успех", 
                           f"✅ Форматирование завершено!\n\n"
                           f"📁 Файл сохранён:\n{result.get('output_path', '')}\n\n"
                           f"Обработано параграфов: {result.get('paragraphs_processed', 0)}")
    
    
    # =============================================================
    # МЕТОД ОБРАБОТКИ ОШИБКИ
    # =============================================================
    
    
    def format_error(self, result):
        """
        Обработка ошибки при форматировании
        
        Args:
            result (dict): Словарь с информацией об ошибке
        
        Returns:
            None: Метод показывает сообщение об ошибке
        
        Note:
            Вызывается в главном потоке при любой ошибке
        """
        # Установка статуса ошибки
        self.status_text.set("❌ Ошибка выполнения")
        # Разблокировка кнопки запуска
        self.run_button.config(state="normal")
        
        # Получение списка ошибок
        errors = result.get('errors', ['Неизвестная ошибка'])
        # Формирование сообщения об ошибке
        error_msg = "❌ Произошли ошибки:\n\n" + "\n".join(errors)
        
        # Запись ошибки в лог
        self.log(error_msg)
        # Показ сообщения об ошибке
        messagebox.showerror("Ошибка", error_msg)
    
    
    # =============================================================
    # МЕТОД ЗАПИСИ В ЛОГ GUI
    # =============================================================
    
    
    def log(self, message):
        """
        Добавляет сообщение в лог GUI
        
        Args:
            message (str): Сообщение для записи в лог
        
        Returns:
            None: Метод добавляет текст в текстовое поле
        
        Note:
            Автоматически добавляет временную метку
        """
        # Установка текстового поля в режим редактирования
        self.log_text.config(state="normal")
        # Получение текущей временной метки
        timestamp = datetime.now().strftime("%H:%M:%S")
        # Вставка сообщения с временной меткой
        self.log_text.insert(tk.END, f"[{timestamp}] {message}\n")
        # Прокрутка к последнему сообщению
        self.log_text.see(tk.END)
        # Установка текстового поля в режим только для чтения
        self.log_text.config(state="disabled")
    
    

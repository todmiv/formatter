        # =========================================================
        # ФРЕЙМ СТАТУСА
        # =========================================================
        
        # Создание фрейма для статуса
        status_frame = ttk.Frame(self.root, padding=10)
        # Размещение фрейма под запуском
        status_frame.pack(fill="x", padx=20)
        
        # Создание метки статуса
